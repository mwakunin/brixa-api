-- Audit actions become rows of a lookup table instead of a CHECK on
-- audit_log (schema.ts, auditActions). A CHECK is rewritten for every new
-- action, and validating it re-reads the whole log under a lock that blocks
-- every audit write. From here on a change that adds an action inserts it
-- into audit_actions in its own migration, and audit_log is not touched.
CREATE TABLE "audit_actions" (
	"action" text PRIMARY KEY NOT NULL
